import { mkdirSync, writeFileSync } from 'node:fs'
import { createRequire } from 'node:module'
const require = createRequire(import.meta.url)

const ids = [
  'logos:aws', 'logos:axios', 'logos:docker-icon', 'logos:firebase',
  'logos:github-actions', 'logos:github-icon', 'logos:javascript',
  'logos:kubernetes', 'logos:mongodb-icon', 'logos:nginx', 'logos:nodejs-icon-alt',
  'logos:pinia', 'logos:pnpm', 'logos:postgresql', 'logos:prisma',
  'logos:puppeteer', 'logos:redis', 'logos:socket-io', 'logos:swagger',
  'logos:typescript-icon', 'logos:unocss', 'logos:vitejs', 'logos:vue',
  'skill-icons:expressjs-dark',
]

const symbolId = (iconId) => `ti-${iconId.replace(/[^a-z0-9]+/gi, '-')}`

const collections = {}
const load = (prefix) => (collections[prefix] ??= require(`@iconify-json/${prefix}/icons.json`))

const symbols = ids.map((id) => {
  const [prefix, name] = id.split(':')
  const col = load(prefix)
  const icon = col.icons[name] ?? col.aliases?.[name]
  if (!icon) throw new Error(`missing icon: ${id}`)
  const src = icon.parent ? col.icons[icon.parent] : icon
  const left = icon.left ?? src.left ?? col.left ?? 0
  const top = icon.top ?? src.top ?? col.top ?? 0
  const width = icon.width ?? src.width ?? col.width ?? 16
  const height = icon.height ?? src.height ?? col.height ?? 16
  return `<symbol id="${symbolId(id)}" viewBox="${left} ${top} ${width} ${height}">${src.body}</symbol>`
})

const sprite =
  `<svg xmlns="http://www.w3.org/2000/svg" xmlns:xlink="http://www.w3.org/1999/xlink">` +
  `<!-- GENERATED by scripts/gen-tag-icons.mjs - do not edit by hand. -->` +
  symbols.join('') +
  `</svg>\n`

mkdirSync('public/icons', { recursive: true })
writeFileSync('public/icons/tags.svg', sprite)
console.log(
  `wrote public/icons/tags.svg — ${ids.length} symbols, ${(Buffer.byteLength(sprite) / 1024).toFixed(1)} KB raw`,
)
